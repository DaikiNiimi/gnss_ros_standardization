#!/usr/bin/env python3
"""R2 auxiliary frames cannot manufacture core observations/navigation.

Committed frames are generated by the optional pinned Rust oracle. This tests
the ROS non-publication/recovery contract, not hidden station/SSR field values.
"""
import json
import math
from pathlib import Path
import unittest
import test_receiver_streams as wire
from test_rtcm_reference import msm
from test_decoder_boundaries import rtcm_payload,RTCM_PARAMS

TABLE=json.loads(Path(__file__).with_name('rtcm_auxiliary_reference.json').read_text())

class AuxiliaryReference(unittest.TestCase):
    def test_count_boundaries_and_long_descriptors_recover(self):
        frames=[]
        for mid in (1007,1008,1033):
            for n in (0,31,32,63,64,255):
                p=((mid<<12)|42).to_bytes(3,'big')+bytes([n])+b'A'*n+b'\x07'
                if mid!=1007:p+=b'\x03SN1'
                if mid==1033:p+=b'\x03ABC'*3
                frames += [rtcm_payload(p),rtcm_payload(p[:-1])]
        # 1230 declares four biases but omits all values.
        frames.append(rtcm_payload(((1230<<20)|(42<<8)|15).to_bytes(4,'big')))
        for case in TABLE['cases']:
            if 1057<=case['id']<=1068 and case['variant']=='empty':
                f=bytes.fromhex(case['frame_hex']);p=bytearray(f[3:-3])
                kind=(case['id']-1057)%6;epochbits=17 if case['id']>=1063 else 20
                offset=12+epochbits+4+1+int(kind in (0,3))+4+16+4
                for bit in range(offset,offset+6):p[bit//8]|=1<<(7-bit%8)
                frames.append(rtcm_payload(p))
        chunks=[]
        for i,f in enumerate(frames):chunks += [f,msm(7,tow_ms=100000+1000*i)]
        r=wire.run('aux_counts','rtcm_decoder_node',chunks,RTCM_PARAMS,chunk_delay=.01)
        self.assertEqual([m.tow for m in r['obs']],[100.+i for i in range(len(frames))])
        for m in r['obs']:
            self.assertEqual((m.week,len(m.observations)),(2300,1))
            self.assertAlmostEqual(m.observations[0].p,(70.5-512*2**-29)*299792.458,delta=1e-6)

    def test_header_only_legacy_messages_cannot_complete_pending_msm(self):
        from test_decoder_boundaries import bits
        frames=[]
        for i,mid in enumerate((1001,1003,1009,1011)):
            old=msm(7,tow_ms=100000+i*2000)
            frames += [bits(old,78,1,1),bytes.fromhex(next(c['frame_hex'] for c in TABLE['cases'] if c['id']==mid)),
                       msm(7,tow_ms=101000+i*2000)]
        r=wire.run('aux_legacy_pending','rtcm_decoder_node',frames,RTCM_PARAMS,chunk_delay=.04)
        self.assertEqual([m.tow for m in r['obs']],[101.,103.,105.,107.])

    def exercise(self,malformed):
        chunks=[]
        for i,case in enumerate(TABLE['cases']):
            frame=bytes.fromhex(case['frame_hex'])
            self.assertEqual((frame[3]<<4)|(frame[4]>>4),case['id'])
            if malformed:
                bad=frame[:-1]+bytes([frame[-1]^1])
                # A valid frame envelope with only the message ID, followed by
                # the same frame with a corrupt CRC. Neither can emit a record.
                chunks.append(rtcm_payload(frame[3:5])+bad)
            else:chunks.append(frame)
            chunks.append(msm(7,tow_ms=100000+i*1000))
        result=wire.run('auxiliary_'+('bad' if malformed else 'reference'),'rtcm_decoder_node',chunks,
                        RTCM_PARAMS+['-p','topics.ephemeris:=/review/nav'],chunk_delay=.01)
        epochs=[e for e in result['obs'] if e.observations]
        self.assertEqual(len(epochs),len(TABLE['cases']))
        wavelength=299792458./1575.42e6
        for i,epoch in enumerate(epochs):
            self.assertEqual((epoch.week,epoch.tow),(2300,100.+i))
            self.assertEqual(len(epoch.observations),1)
            o=epoch.observations[0]
            self.assertEqual((o.system,o.prn,o.code_str,o.freq),('G',1,'1C',255))
            self.assertAlmostEqual(o.p,(70.5-512*2**-29)*299792.458,delta=1e-6)
            self.assertAlmostEqual(o.l,(70.5+4096*2**-31)*299792.458/wavelength,delta=1e-6)
            self.assertTrue(math.isclose(o.d,100.1234/wavelength,rel_tol=1e-7,abs_tol=1e-5))
            self.assertEqual(o.snr,45.0625);self.assertEqual(o.lli&2,2)
        self.assertFalse(result['sol'] or result['imu'] or result['raw'])
        self.assertFalse(any(m.gnss_ephemeris or m.glonass_ephemeris for m in result['nav']))

    def test_reference_records_do_not_emit_core_data_and_recover(self):self.exercise(False)
    def test_short_payload_bad_crc_do_not_contaminate_recovery(self):self.exercise(True)

if __name__=='__main__':unittest.main(argv=[__file__]+wire.unittest_args)
